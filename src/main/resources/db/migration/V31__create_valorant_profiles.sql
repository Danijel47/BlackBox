CREATE TABLE valorant_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_name VARCHAR(64) NOT NULL,
    puuid VARCHAR(128) NOT NULL UNIQUE,
    riot_id VARCHAR(128) NOT NULL,
    region VARCHAR(16) NOT NULL,
    platform VARCHAR(16) NOT NULL CHECK (platform IN ('pc', 'console')),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX valorant_profile_name_lower_unique ON valorant_profile (LOWER(profile_name));
